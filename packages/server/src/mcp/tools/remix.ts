import { z } from 'zod';
import { findNode } from '@mockup/core';
import { REMIX_MAX_COUNT } from '../../remix.js';
import { ToolError, WRITE, docIdField, type ToolContext } from '../context.js';

const KINDS = ['color-scale', 'font-pairs', 'spacing', 'layout', 'ai'] as const;

/** How many created frames go into the response summary (the rest only appear in the id list). */
const SUMMARY_FRAMES = 3;

export function registerRemixTools(ctx: ToolContext): void {
  const { tool, store, opts } = ctx;

  tool(
    'remix',
    {
      title: 'Remix: side-by-side variations',
      description:
        'Creates variations of a node as cloned frames side by side to the right (one undo reverts everything). kind: color-scale (10 shades), font-pairs, spacing, layout or ai (requires prompt and the assistant). Returns the ids; check with get_screenshot.',
      example: { nodeId: 'el_ab12cd34', kind: 'color-scale', count: 5 },
      inputSchema: {
        nodeId: z
          .string()
          .describe('Node to vary, e.g. "el_ab12cd34"; the root frame that contains it is cloned.'),
        kind: z
          .enum(KINDS)
          .describe(
            '"color-scale" (shades 50-900 of the node color), "font-pairs" (local font pairs), "spacing" (4/8 scale), "layout" (flex rearrangements) or "ai" (variations generated by the assistant).',
          ),
        count: z
          .number()
          .int()
          .min(1)
          .max(REMIX_MAX_COUNT)
          .optional()
          .describe(
            'How many variations, 1 to 10, e.g. 5. Default: color-scale 10, font-pairs 4, spacing 4, layout 3, ai 3.',
          ),
        prompt: z
          .string()
          .optional()
          .describe(
            'Required for kind "ai": how the variations should differ, e.g. "bolder versions".',
          ),
        docId: docIdField,
      },
      annotations: WRITE,
    },
    async ({ nodeId, kind, count, prompt, docId }) => {
      const remix = opts.services?.remix;
      if (!remix) throw new ToolError('Remix is unavailable in this daemon.');
      const id = store.resolveDocId(docId);
      if (kind === 'ai' && !prompt?.trim())
        throw new ToolError(
          'kind "ai" requires prompt. E.g. { nodeId: "fr_ab12cd34", kind: "ai", prompt: "bolder versions" }.',
        );
      ctx.requireNode(store.get(id), nodeId);
      const r = await remix.run(id, nodeId, kind, {
        ...(count !== undefined ? { count } : {}),
        ...(prompt !== undefined ? { prompt } : {}),
        group: ctx.group(),
        source: 'mcp',
      });
      const doc = store.get(id);
      if (r.frameIds.length === 0)
        return 'The assistant finished without creating new frames. Check the page with get_basic_info.';
      const lines = r.frameIds.map((fid, i) => {
        const name = findNode(doc, fid)?.node.name ?? r.labels[i] ?? '';
        return `- ${fid} "${name}"`;
      });
      const shown = r.frameIds.slice(0, SUMMARY_FRAMES);
      const more =
        r.frameIds.length > shown.length
          ? ` (summary of the first ${shown.length} of ${r.frameIds.length})`
          : '';
      return `${r.frameIds.length} variation(s) created side by side${kind === 'ai' ? ' by the assistant' : ''}; one undo reverts them all.\n${lines.join('\n')}\nSummary${more}:\n${ctx.summaryOf(doc, shown)}`;
    },
  );
}

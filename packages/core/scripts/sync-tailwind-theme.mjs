// Copies Tailwind's default theme (`tailwindcss/theme.css`) into a TS module in core, which does not read
// files (it runs in the daemon, the editor and Electron). Run after updating `tailwindcss`:
//   node packages/core/scripts/sync-tailwind-theme.mjs
// The `tailwind/theme.test.ts` test fails if the generated module is out of date.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const pkgDir = path.dirname(require.resolve('tailwindcss/package.json'));
const version = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8')).version;
const css = fs.readFileSync(path.join(pkgDir, 'theme.css'), 'utf8').replace(/\r\n/g, '\n');
const out = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  '../src/tailwind/theme.generated.ts',
);
fs.writeFileSync(
  out,
  [
    '// Generated by scripts/sync-tailwind-theme.mjs from tailwindcss/theme.css (MIT). Do not edit.',
    `export const TAILWIND_VERSION = ${JSON.stringify(version)};`,
    `export const TAILWIND_THEME_CSS = ${JSON.stringify(css)};`,
    '',
  ].join('\n'),
);
process.stdout.write(
  `theme.generated.ts updated (tailwindcss ${version}, ${css.length} characters)\n`,
);

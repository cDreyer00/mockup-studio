/**
 * Node states (`node.states`): styles that only apply under a condition, like Tailwind
 * variants. The key is the chain of variants in canonical order, separated by `:`:
 *
 *   [breakpoint] [dark] [pseudo]      e.g. `hover`, `dark`, `md`, `md:hover`, `dark:hover`, `lg:dark:focus`
 *
 * - breakpoint (`sm`, `md`, `lg`, `xl`, `2xl`): applies when the root frame width is greater than
 *   or equal to the breakpoint (mobile first, as in Tailwind; the frame is the design viewport);
 * - `dark`: applies inside a frame/node with `data-theme="dark"` or in the editor's "dark" preview;
 * - pseudo (`hover`, `focus`, `focus-visible`, `focus-within`, `active`, `disabled`): applies in the
 *   state preview (editor, `get_screenshot(state)`) and in the exported code.
 */
import type { Node } from './types.js';

/** Tailwind's `dark:` variant in Mockup Studio: the document's `dark` theme (`data-theme` attribute). */
export const DARK_VARIANT_CSS =
  '@custom-variant dark (&:where([data-theme=dark], [data-theme=dark] *));';

export const BREAKPOINTS = ['sm', 'md', 'lg', 'xl', '2xl'] as const;
export type Breakpoint = (typeof BREAKPOINTS)[number];

/** Default minimum widths of Tailwind v4 (`--breakpoint-*`, in px). */
export const BREAKPOINT_PX: Record<Breakpoint, number> = {
  sm: 640,
  md: 768,
  lg: 1024,
  xl: 1280,
  '2xl': 1536,
};

/**
 * Breakpoint widths of the document: `--breakpoint-<bp>` in `doc.tokens` (px or rem, the same
 * the Tailwind engine compiles into `md:`), with the Tailwind default for any that are missing.
 */
export function breakpointsOf(doc: {
  tokens?: Record<string, string>;
}): Record<Breakpoint, number> {
  const out = { ...BREAKPOINT_PX };
  for (const bp of BREAKPOINTS) {
    const px = fixedWidthPx(doc.tokens?.[`--breakpoint-${bp}`]);
    if (px !== undefined) out[bp] = px;
  }
  return out;
}

export const PSEUDO_STATES = [
  'hover',
  'focus',
  'focus-visible',
  'focus-within',
  'active',
  'disabled',
] as const;
export type PseudoState = (typeof PSEUDO_STATES)[number];

/** States that the editor preview and `get_screenshot(state)` accept. */
export const PREVIEW_STATES = [...PSEUDO_STATES, 'dark'] as const;
export type PreviewState = (typeof PREVIEW_STATES)[number];

export interface StateKeyParts {
  breakpoint?: Breakpoint;
  dark?: boolean;
  pseudo?: PseudoState;
}

const isBreakpoint = (s: string): s is Breakpoint => (BREAKPOINTS as readonly string[]).includes(s);
const isPseudo = (s: string): s is PseudoState => (PSEUDO_STATES as readonly string[]).includes(s);

/**
 * Parses a chain of variants (`hover`, `md:hover`, `hover:dark`...) in any order. `null` if
 * any part is unsupported, if a category repeats or if it is empty.
 */
export function parseStateKey(key: string): StateKeyParts | null {
  const parts = key.split(':').map((p) => p.trim());
  if (parts.length === 0 || parts.some((p) => p === '')) return null;
  const out: StateKeyParts = {};
  for (const p of parts) {
    if (isBreakpoint(p)) {
      if (out.breakpoint) return null;
      out.breakpoint = p;
    } else if (p === 'dark') {
      if (out.dark) return null;
      out.dark = true;
    } else if (isPseudo(p)) {
      if (out.pseudo) return null;
      out.pseudo = p;
    } else return null;
  }
  return out;
}

/** Canonical key (`breakpoint:dark:pseudo`). */
export function formatStateKey(parts: StateKeyParts): string {
  const out: string[] = [];
  if (parts.breakpoint) out.push(parts.breakpoint);
  if (parts.dark) out.push('dark');
  if (parts.pseudo) out.push(parts.pseudo);
  return out.join(':');
}

/** Normalizes the key to its canonical form; `null` if invalid. */
export function normalizeStateKey(key: string): string | null {
  const p = parseStateKey(key);
  if (!p) return null;
  const k = formatStateKey(p);
  return k === '' ? null : k;
}

/**
 * Application order (like the cascade of the CSS generated by Tailwind): states with a
 * pseudo-class (more specific) last; among equals, smaller breakpoints first and `dark` after.
 */
export function stateOrder(key: string): number {
  const p = parseStateKey(key);
  if (!p) return Number.MAX_SAFE_INTEGER;
  const bp = p.breakpoint ? BREAKPOINTS.indexOf(p.breakpoint) + 1 : 0;
  return (p.pseudo ? 100 : 0) + bp * 10 + (p.dark ? 5 : 0);
}

/** Keys sorted by application order. */
export function sortStateKeys(keys: string[]): string[] {
  return [...keys].sort((a, b) => stateOrder(a) - stateOrder(b) || a.localeCompare(b));
}

export interface StateContext {
  /** Root frame width in px (activates breakpoints). Absent: no breakpoint. */
  frameWidth?: number;
  /** Node inside a `dark` theme (or "dark" preview). */
  dark?: boolean;
  /** Pseudo-state in preview (hover, focus...). */
  pseudo?: PseudoState | null;
  /** Breakpoint widths (default: `BREAKPOINT_PX`). */
  breakpoints?: Partial<Record<Breakpoint, number>>;
}

/** Is the `key` state active in the context? */
export function stateMatches(key: string, ctx: StateContext): boolean {
  const p = parseStateKey(key);
  if (!p) return false;
  if (p.breakpoint) {
    const min = ctx.breakpoints?.[p.breakpoint] ?? BREAKPOINT_PX[p.breakpoint];
    if (ctx.frameWidth === undefined || ctx.frameWidth < min) return false;
  }
  if (p.dark && !ctx.dark) return false;
  if (p.pseudo && ctx.pseudo !== p.pseudo) return false;
  return true;
}

/** `true` if the node has any state with styles. */
export function hasStates(node: Node): boolean {
  return !!node.states && Object.values(node.states).some((s) => Object.keys(s).length > 0);
}

/**
 * Effective style of the node in the context: `node.style` with the active states applied on
 * top, in `stateOrder` order. Without states returns `node.style` itself.
 */
export function resolveStateStyle(node: Node, ctx: StateContext): Record<string, string> {
  if (!node.states) return node.style;
  const active = sortStateKeys(Object.keys(node.states)).filter((k) => stateMatches(k, ctx));
  if (active.length === 0) return node.style;
  const out = { ...node.style };
  for (const k of active) Object.assign(out, node.states[k]);
  return out;
}

/** Width in px of a simple CSS value (`1280px`, `80rem`); `undefined` if not fixed. */
export function fixedWidthPx(value: string | undefined): number | undefined {
  if (!value) return undefined;
  const m = /^\s*(\d+(?:\.\d+)?|\.\d+)(px|rem)?\s*$/.exec(value);
  if (!m) return undefined;
  const n = parseFloat(m[1]);
  return m[2] === 'rem' ? n * 16 : n;
}
